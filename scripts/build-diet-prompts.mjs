/**
 * Writes src/lib/diet/promptText.js from prompts/*.md.
 *
 * The prompts are reviewed as Markdown in prompts/ (the Diet build spec
 * asks for them there), but a Supabase edge function imports JavaScript,
 * not Markdown, without extra deploy configuration. So the Markdown is the
 * source and this script makes the JavaScript copy; tests/diet-prompts.test.js
 * fails when the two disagree, which is the reminder to run it.
 *
 *   node scripts/build-diet-prompts.mjs
 *
 * Added for the Diet module, Phase 2 (docs/diet-module.md).
 */

import { readFileSync, writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import { dirname, join } from 'node:path'

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..')

export const PROMPT_FILES = [
  ['food-vision', 'FOOD_VISION_MD'],
  ['coach', 'COACH_MD'],
  ['text-parse', 'TEXT_PARSE_MD'],
]

const literal = (s) => '`' + s.replace(/\\/g, '\\\\').replace(/`/g, '\\`').replace(/\$\{/g, '\\${') + '`'

export function buildPromptModule(read = (name) => readFileSync(join(ROOT, 'prompts', `${name}.md`), 'utf8')) {
  const head = `/**
 * GENERATED by scripts/build-diet-prompts.mjs from prompts/*.md. Do not
 * edit: change the Markdown and run \`node scripts/build-diet-prompts.mjs\`.
 * The logic that uses these lives in ./prompts.js.
 */
`
  return head + PROMPT_FILES.map(([name, constant]) => `\n// prompts/${name}.md\nexport const ${constant} = ${literal(read(name))}\n`).join('')
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  writeFileSync(join(ROOT, 'src', 'lib', 'diet', 'promptText.js'), buildPromptModule())
  console.log('wrote src/lib/diet/promptText.js')
}
